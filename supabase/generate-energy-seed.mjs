// Generates supabase/seed.energy.sql from src/data/energy.content.json.
// Run from the website/ dir:  node supabase/generate-energy-seed.mjs
//
// The JSON itself comes from the research workbook via
// supabase/xlsx-to-energy-json.py, so the full chain is:
//   us_renewable_policy_data.xlsx -> energy.content.json -> seed.energy.sql
// Re-run both steps whenever a refreshed workbook lands.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const jsonPath = join(here, '..', 'src', 'data', 'energy.content.json');
const outPath = join(here, 'seed.energy.sql');

const dataset = JSON.parse(readFileSync(jsonPath, 'utf-8'));
const { policies, documents, links, assessments } = dataset;

// Single-quote escaping for SQL string literals.
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === null || v === undefined ? 'null' : Number(v));
const bool = (v) => (v ? 'true' : 'false');
/** Postgres text[] literal, e.g. array['a','b'] — empty stays a typed array. */
const arr = (v) =>
  !v || v.length === 0 ? "'{}'::text[]" : `array[${v.map(q).join(', ')}]::text[]`;

/** Builds one multi-row INSERT, or a comment when the table has no rows. */
function insert(table, columns, rows) {
  if (rows.length === 0) return `-- no rows for public.${table}`;
  return (
    `insert into public.${table} (${columns.join(', ')}) values\n` +
    rows.map((r) => `  (${r.join(', ')})`).join(',\n') +
    ';'
  );
}

const lines = [];
lines.push('-- AUTO-GENERATED by supabase/generate-energy-seed.mjs — do not edit by hand.');
lines.push('-- Run this in the Supabase SQL Editor AFTER schema.energy.sql.');
lines.push('-- Safe to re-run: it clears all four tables first.');
lines.push(`-- Dataset status as of ${dataset.meta?.statusAsOf ?? 'unknown'}.`);
lines.push('');
lines.push(
  'truncate table public.policy_status_assessments, public.policy_document_links,',
);
lines.push('  public.policy_documents, public.policies restart identity cascade;');
lines.push('');

lines.push(
  insert(
    'policies',
    [
      'policy_id', 'pillar_slug', 'policy_title', 'policy_area', 'short_summary',
      'legal_status', 'implementation_status', 'litigation_status', 'status_as_of',
      'status_explanation', 'effective_requirements', 'inactive_or_limited_scope',
      'lead_agencies', 'affected_entities', 'next_milestone', 'confidence',
      'review_status', 'sort_order',
    ],
    policies.map((p, i) => [
      q(p.policy_id), q('energy'), q(p.policy_title), q(p.policy_area), q(p.short_summary),
      q(p.legal_status), q(p.implementation_status), q(p.litigation_status), q(p.status_as_of),
      q(p.status_explanation), q(p.effective_requirements), q(p.inactive_or_limited_scope),
      arr(p.lead_agencies), arr(p.affected_entities), q(p.next_milestone), q(p.confidence),
      q(p.review_status), i,
    ]),
  ),
);
lines.push('');

lines.push(
  insert(
    'policy_documents',
    [
      'document_id', 'document_type', 'title', 'issuing_body', 'publication_date',
      'effective_date', 'official_identifier', 'official_page_url', 'official_text_url',
      'citation_locator', 'proposition_supported', 'source_tier', 'document_effect',
      'link_checked_at', 'link_status', 'is_legal_anchor', 'notes',
    ],
    documents.map((d) => [
      q(d.document_id), q(d.document_type), q(d.title), q(d.issuing_body), q(d.publication_date),
      q(d.effective_date), q(d.official_identifier), q(d.official_page_url), q(d.official_text_url),
      q(d.citation_locator), q(d.proposition_supported), num(d.source_tier), q(d.document_effect),
      q(d.link_checked_at), q(d.link_status), bool(d.is_legal_anchor), q(d.notes),
    ]),
  ),
);
lines.push('');

lines.push(
  insert(
    'policy_document_links',
    [
      'link_id', 'policy_id', 'document_id', 'relationship_type', 'relationship_summary',
      'scope_affected', 'valid_from', 'valid_to', 'is_controlling_source',
    ],
    links.map((l) => [
      q(l.link_id), q(l.policy_id), q(l.document_id), q(l.relationship_type),
      q(l.relationship_summary), q(l.scope_affected), q(l.valid_from), q(l.valid_to),
      bool(l.is_controlling_source),
    ]),
  ),
);
lines.push('');

lines.push(
  insert(
    'policy_status_assessments',
    [
      'assessment_id', 'policy_id', 'assessment_date', 'assessment_type', 'assessment_value',
      'assessment_summary', 'primary_document_id', 'supporting_document_ids',
      'citation_locator', 'analyst_inference', 'confidence', 'reviewer_status',
    ],
    assessments.map((a) => [
      q(a.assessment_id), q(a.policy_id), q(a.assessment_date), q(a.assessment_type),
      q(a.assessment_value), q(a.assessment_summary), q(a.primary_document_id),
      arr(a.supporting_document_ids), q(a.citation_locator), bool(a.analyst_inference),
      q(a.confidence), q(a.reviewer_status),
    ]),
  ),
);
lines.push('');

writeFileSync(outPath, lines.join('\n'), 'utf-8');
console.log(
  `Wrote ${outPath} (${policies.length} policies, ${documents.length} documents, ` +
    `${links.length} links, ${assessments.length} assessments)`,
);
