const q = (value) =>
  value === null || value === undefined
    ? 'null'
    : `'${String(value).replace(/'/g, "''")}'`;

const num = (value) =>
  value === null || value === undefined ? 'null' : Number(value);

const bool = (value) => (value ? 'true' : 'false');

const arr = (value) =>
  !value || value.length === 0
    ? "'{}'::text[]"
    : `array[${value.map(q).join(', ')}]::text[]`;

function insert(table, columns, rows) {
  if (rows.length === 0) return `-- no rows for public.${table}`;
  return (
    `insert into public.${table} (${columns.join(', ')}) values\n` +
    rows.map((row) => `  (${row.join(', ')})`).join(',\n') +
    ';'
  );
}

export function renderPolicySeed(dataset, areas) {
  const { policies, documents, links, assessments } = dataset;
  const lines = [];
  lines.push('-- AUTO-GENERATED by supabase/generate-policy-seed.mjs — do not edit by hand.');
  lines.push('-- Run this in the Supabase SQL Editor AFTER schema.sql.');
  lines.push('-- Safe to re-run: it clears all policy tables first.');
  lines.push(`-- Dataset status as of ${dataset.meta?.statusAsOf ?? 'unknown'}.`);
  lines.push('');
  lines.push(
    'truncate table public.policy_status_assessments, public.policy_document_links,',
  );
  lines.push(
    '  public.policy_documents, public.policies, public.policy_areas restart identity cascade;',
  );
  lines.push('');

  lines.push(
    insert(
      'policy_areas',
      ['slug', 'label', 'description', 'sort_order'],
      areas.map((area) => [
        q(area.slug), q(area.label), q(area.description), num(area.sort_order),
      ]),
    ),
  );
  lines.push('');

  lines.push(
    insert(
      'policies',
      [
        'policy_id', 'policy_area_slug', 'source_policy_area', 'policy_title',
        'short_summary', 'legal_status', 'implementation_status', 'litigation_status',
        'status_as_of', 'status_explanation', 'effective_requirements',
        'inactive_or_limited_scope', 'lead_agencies', 'affected_entities',
        'next_milestone', 'confidence', 'review_status', 'sort_order',
      ],
      policies.map((policy) => [
        q(policy.policy_id), q(policy.policy_area_slug), q(policy.source_policy_area),
        q(policy.policy_title), q(policy.short_summary), q(policy.legal_status),
        q(policy.implementation_status), q(policy.litigation_status), q(policy.status_as_of),
        q(policy.status_explanation), q(policy.effective_requirements),
        q(policy.inactive_or_limited_scope), arr(policy.lead_agencies),
        arr(policy.affected_entities), q(policy.next_milestone), q(policy.confidence),
        q(policy.review_status), num(policy.sort_order),
      ]),
    ),
  );
  lines.push('');

  lines.push(
    insert(
      'policy_documents',
      [
        'document_id', 'document_type', 'title', 'issuing_body', 'publication_date',
        'effective_date', 'official_identifier', 'official_page_url', 'official_text_url',
        'citation_locator', 'proposition_supported', 'source_tier', 'document_effect',
        'link_checked_at', 'link_status', 'is_legal_anchor', 'notes',
      ],
      documents.map((document) => [
        q(document.document_id), q(document.document_type), q(document.title),
        q(document.issuing_body), q(document.publication_date), q(document.effective_date),
        q(document.official_identifier), q(document.official_page_url),
        q(document.official_text_url), q(document.citation_locator),
        q(document.proposition_supported), num(document.source_tier),
        q(document.document_effect), q(document.link_checked_at), q(document.link_status),
        bool(document.is_legal_anchor), q(document.notes),
      ]),
    ),
  );
  lines.push('');

  lines.push(
    insert(
      'policy_document_links',
      [
        'link_id', 'policy_id', 'document_id', 'relationship_type',
        'relationship_summary', 'scope_affected', 'valid_from', 'valid_to',
        'is_controlling_source',
      ],
      links.map((link) => [
        q(link.link_id), q(link.policy_id), q(link.document_id),
        q(link.relationship_type), q(link.relationship_summary), q(link.scope_affected),
        q(link.valid_from), q(link.valid_to), bool(link.is_controlling_source),
      ]),
    ),
  );
  lines.push('');

  lines.push(
    insert(
      'policy_status_assessments',
      [
        'assessment_id', 'policy_id', 'assessment_date', 'assessment_type',
        'assessment_value', 'assessment_summary', 'primary_document_id',
        'supporting_document_ids', 'citation_locator', 'analyst_inference',
        'confidence', 'reviewer_status',
      ],
      assessments.map((assessment) => [
        q(assessment.assessment_id), q(assessment.policy_id), q(assessment.assessment_date),
        q(assessment.assessment_type), q(assessment.assessment_value),
        q(assessment.assessment_summary), q(assessment.primary_document_id),
        arr(assessment.supporting_document_ids), q(assessment.citation_locator),
        bool(assessment.analyst_inference), q(assessment.confidence),
        q(assessment.reviewer_status),
      ]),
    ),
  );
  lines.push('');

  return lines.join('\n');
}
